namespace WAD.NET.UDMF.Fields
{
    /// <summary>
    /// Vertex
    /// </summary>
    /// <remarks>
    /// As defined by UDMF 1.1
    /// <see cref="https://github.com/coelckers/gzdoom/blob/master/specs/udmf.txt"/>
    /// </remarks>
    struct Vertex
    {
        /// <summary>
        /// X coordinate. No valid default.
        /// </summary>
        double x;

        /// <summary>
        /// Y coordinate. No valid default.
        /// </summary>
        double y;
    }
}
